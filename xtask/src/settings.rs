use std::{
    fs,
    io::Write,
    path::Path,
    process::{Command, Stdio},
};

use anyhow::{Context, Result, bail};
use jjpwrgem_parse::format::FormatConfig;
use proc_macro2::Literal;
use quote::quote;
use schemars::generate::SchemaSettings;
use serde_json::{Map, Value};

const WORKSPACE_ROOT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/..");
const FORMAT_SETTINGS_RS: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../crates/cli/format_settings.rs"
);
const GENERATED_MARKER: &str = "// @generated by cargo xtask generate-settings\n\n";
const REGENERATE_HINT: &str = "run `cargo xtask generate-settings`";

enum Kind {
    Integer {
        default: u64,
    },
    Choice {
        values: Vec<String>,
        default: String,
    },
}

struct Setting {
    name: String,
    description: String,
    kind: Kind,
}

impl Setting {
    fn flag(&self) -> String {
        self.name.chars().fold(String::new(), |mut flag, c| {
            if c.is_uppercase() {
                flag.push('-');
            }
            flag.extend(c.to_lowercase());
            flag
        })
    }

    fn rust_tokens(&self) -> proc_macro2::TokenStream {
        let (name, flag, description) = (&self.name, self.flag(), &self.description);
        let kind = match &self.kind {
            Kind::Integer { default } => {
                let default = Literal::u64_unsuffixed(*default);
                quote!(SettingKind::Integer { default: #default })
            }
            Kind::Choice { values, default } => quote!(SettingKind::Choice {
                values: &[#(#values),*],
                default: #default,
            }),
        };
        quote!(Setting { name: #name, flag: #flag, description: #description, kind: #kind })
    }
}

fn parse_setting(name: &str, property: &Map<String, Value>) -> Result<Setting> {
    let text = |key| {
        property
            .get(key)
            .and_then(Value::as_str)
            .map(str::to_owned)
            .with_context(|| format!("setting {name} has no string {key}"))
    };
    let kind = match property.get("enum").and_then(Value::as_array) {
        Some(values) => Kind::Choice {
            values: values
                .iter()
                .filter_map(|value| value.as_str().map(str::to_owned))
                .collect(),
            default: text("default")?,
        },
        None => Kind::Integer {
            default: property
                .get("default")
                .and_then(Value::as_u64)
                .with_context(|| format!("setting {name} has no integer default"))?,
        },
    };
    Ok(Setting {
        name: name.to_owned(),
        description: text("description")?,
        kind,
    })
}

fn format_settings() -> Result<Vec<Setting>> {
    let schema = SchemaSettings::draft07()
        .with(|settings| settings.inline_subschemas = true)
        .into_generator()
        .into_root_schema_for::<FormatConfig>();
    schema
        .get("properties")
        .and_then(Value::as_object)
        .into_iter()
        .flatten()
        .map(|(name, property)| {
            parse_setting(
                name,
                property.as_object().context("setting is not an object")?,
            )
        })
        .collect()
}

fn rustfmt(source: &str) -> Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024"])
        .current_dir(Path::new(WORKSPACE_ROOT))
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()?;
    child
        .stdin
        .take()
        .context("rustfmt has no stdin")?
        .write_all(source.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        bail!("rustfmt failed on the generated settings");
    }
    Ok(String::from_utf8(output.stdout)?)
}

fn render_rust(settings: &[Setting]) -> Result<String> {
    let settings = settings.iter().map(Setting::rust_tokens);
    let tokens = quote! {
        use jjpwrgem_parse::format::{Setting, SettingKind};

        pub const FORMAT_SETTINGS: &[Setting] = &[#(#settings),*];
    };
    Ok(format!(
        "{GENERATED_MARKER}{}",
        rustfmt(&tokens.to_string())?
    ))
}

pub fn write_settings() -> Result<()> {
    fs::write(FORMAT_SETTINGS_RS, render_rust(&format_settings()?)?)?;
    println!("generated settings");
    Ok(())
}

pub fn are_settings_updated() -> Result<()> {
    if render_rust(&format_settings()?)? != fs::read_to_string(FORMAT_SETTINGS_RS)? {
        bail!("cli format settings are out of date, {REGENERATE_HINT}");
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn preferred_width_is_only_set_when_present() {
        let width = |json| serde_json::from_str::<FormatConfig>(json).map(|c| c.preferred_width);
        assert_eq!(width(r#"{"preferredWidth": 100}"#).unwrap(), Some(100));
        assert_eq!(width("{}").unwrap(), None);
    }

    #[test]
    fn generation_is_idempotent_on_the_committed_file() {
        let committed = fs::read_to_string(FORMAT_SETTINGS_RS).unwrap();
        assert_eq!(render_rust(&format_settings().unwrap()).unwrap(), committed);
    }
}
